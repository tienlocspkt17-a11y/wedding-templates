// Canonical catalog metadata shared by the 38-template gallery and the
// Universal Editor.  The public showcase uses numbered ids (suite-11,
// classic-21, ...), while the renderer uses semantic ids (editorial,
// watercolor-romance, ...).  Keeping the mapping here prevents an editor
// link from silently opening the wrong template or falling back to the picker.
const EA_GROUP_META = {
  cinematic: { prefix: 'cinematic', start: 1, rendererFamily: 'cinematic' },
  suite: { prefix: 'suite', start: 11, rendererFamily: 'suite' },
  classic: { prefix: 'classic', start: 21, rendererFamily: 'core' },
  signature: { prefix: 'signature', start: 31, rendererFamily: 'core' }
};
const EA_GROUP_INDEX = Object.create(null);

window.EA_STYLES.forEach(style => {
  const meta = EA_GROUP_META[style.group] || {
    prefix: style.group || 'custom',
    start: 1,
    rendererFamily: 'core'
  };
  const index = EA_GROUP_INDEX[style.group] || 0;
  EA_GROUP_INDEX[style.group] = index + 1;
  const catalogNumber = meta.start + index;

  style.catalogNumber = String(catalogNumber).padStart(2, '0');
  style.catalogId = `${meta.prefix}-${String(catalogNumber).padStart(2, '0')}`;
  style.rendererFamily = meta.rendererFamily;
  style.editorCapabilities = {
    text: true,
    image: true,
    sectionOrder: true,
    sectionVisibility: true,
    notes: true
  };
});

window.EA_CATALOG = Object.freeze({
  count: window.EA_STYLES.length,
  groups: Object.freeze(EA_GROUP_META),
  styles: window.EA_STYLES
});
